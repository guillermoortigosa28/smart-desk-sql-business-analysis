-- SMART DESK | Independent business analysis
-- Grain check: one SALES row is a recorded account/category/quarter entry,
-- not necessarily a unique order. Do not label COUNT(*) as order count.

-- EDA 1. Coverage and distribution.
SELECT COUNT(*) AS SALES_RECORDS,
       COUNT(DISTINCT ACCOUNT) AS UNIQUE_ACCOUNTS,
       ROUND(AVG(PROFIT), 2) AS AVG_PROFIT_PER_RECORD,
       ROUND(STDDEV_SAMP(PROFIT), 2) AS STDDEV_PROFIT,
       MIN(PROFIT) AS MIN_PROFIT,
       MAX(PROFIT) AS MAX_PROFIT,
       ROUND(AVG(UNITS_SOLD), 2) AS AVG_UNITS,
       ROUND(STDDEV_SAMP(UNITS_SOLD), 2) AS STDDEV_UNITS
FROM SALES;

-- EDA 2. Profit distribution by product category.
SELECT CATEGORY, COUNT(*) AS SALES_RECORDS,
       ROUND(AVG(PROFIT), 2) AS AVG_PROFIT,
       MIN(PROFIT) AS MIN_PROFIT,
       MAX(PROFIT) AS MAX_PROFIT,
       ROUND(STDDEV_SAMP(PROFIT), 2) AS STDDEV_PROFIT
FROM SALES
GROUP BY CATEGORY
ORDER BY AVG_PROFIT DESC;

-- EDA 3. Revenue, profit and margin by category.
SELECT CATEGORY, COUNT(*) AS SALES_RECORDS,
       ROUND(SUM(TOTAL), 2) AS TOTAL_REVENUE,
       ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
       ROUND(100.0 * SUM(PROFIT) / NULLIF(SUM(TOTAL), 0), 2) AS PROFIT_MARGIN_PCT
FROM SALES
GROUP BY CATEGORY
ORDER BY PROFIT_MARGIN_PCT DESC;

-- EDA 4. Annual trend (2019-2021 actuals).
SELECT YEAR, COUNT(*) AS SALES_RECORDS,
       SUM(TOTAL) AS TOTAL_REVENUE,
       SUM(PROFIT) AS TOTAL_PROFIT,
       ROUND(100.0 * SUM(PROFIT) / NULLIF(SUM(TOTAL), 0), 2) AS PROFIT_MARGIN_PCT
FROM SALES
GROUP BY YEAR
ORDER BY YEAR;

-- EDA 5. Industry performance, weighted margin.
SELECT A.INDUSTRY,
       COUNT(*) AS SALES_RECORDS,
       COUNT(DISTINCT S.ACCOUNT) AS UNIQUE_ACCOUNTS,
       ROUND(SUM(S.TOTAL), 2) AS TOTAL_REVENUE,
       ROUND(SUM(S.PROFIT), 2) AS TOTAL_PROFIT,
       ROUND(AVG(S.PROFIT), 2) AS AVG_PROFIT_PER_RECORD,
       ROUND(100.0 * SUM(S.PROFIT) / NULLIF(SUM(S.TOTAL), 0), 2) AS PROFIT_MARGIN_PCT
FROM SALES S
JOIN ACCOUNTS A ON S.ACCOUNT = A.ACCOUNT
GROUP BY A.INDUSTRY
ORDER BY AVG_PROFIT_PER_RECORD DESC;
