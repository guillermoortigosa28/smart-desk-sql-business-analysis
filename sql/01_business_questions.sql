-- SMART DESK | Snowflake SQL | Four business questions
-- Prerequisite: SALES, ACCOUNTS, FORECASTS available in current schema.
-- Each query can be executed independently.

-- Q1. Sales performance by category for Adabs Entertainment in 2020.
SELECT
    CATEGORY AS CATEGORY,
    SUM(COALESCE(MAINTENANCE, 0)) AS MAINTENANCE_REVENUE,
    SUM(COALESCE(PRODUCT, 0)) AS PRODUCT_REVENUE,
    SUM(COALESCE(PARTS, 0)) AS PARTS_REVENUE,
    SUM(COALESCE(SUPPORT, 0)) AS SUPPORT_REVENUE,
    SUM(TOTAL) AS TOTAL_REVENUE,
    SUM(UNITS_SOLD) AS UNITS_SOLD,
    SUM(PROFIT) AS TOTAL_PROFIT,
    ROUND(100.0 * SUM(PROFIT) / NULLIF(SUM(TOTAL), 0), 2) AS PROFIT_MARGIN_PCT
FROM SALES
WHERE ACCOUNT = 'Adabs Entertainment' AND YEAR = 2020
GROUP BY CATEGORY
ORDER BY CATEGORY;

-- Q2. Mean sales metrics per SALES record, by country and region.
-- These are per-record averages, NOT per-country total revenue.
SELECT
    A.REGION,
    A.COUNTRY,
    COUNT(*) AS SALES_RECORDS,
    ROUND(AVG(S.TOTAL), 2) AS AVG_REVENUE,
    ROUND(AVG(S.UNITS_SOLD), 2) AS AVG_UNITS_SOLD,
    ROUND(AVG(S.PROFIT), 2) AS AVG_PROFIT
FROM ACCOUNTS A
JOIN SALES S ON A.ACCOUNT = S.ACCOUNT
WHERE A.REGION IN ('APAC', 'EMEA')
GROUP BY A.REGION, A.COUNTRY
ORDER BY A.REGION, A.COUNTRY;

-- Q3. Industries associated with accounts having >$500k total
-- forecast in the Commit stage. DISTINCT is redundant with GROUP BY,
-- but is included to make the account-level uniqueness explicit.
SELECT
    A.INDUSTRY,
    SUM(S.PROFIT) AS TOTAL_PROFIT,
    CASE WHEN SUM(S.PROFIT) > 1000000 THEN 'High'
         ELSE 'Normal' END AS PROFIT_CATEGORY
FROM SALES S
JOIN ACCOUNTS A ON S.ACCOUNT = A.ACCOUNT
WHERE S.ACCOUNT IN (
    SELECT DISTINCT ACCOUNT
    FROM FORECASTS
    WHERE PREDICTION_CATEGORY = 'Commit'
    GROUP BY ACCOUNT
    HAVING SUM(FORECAST) > 500000
)
GROUP BY A.INDUSTRY
ORDER BY TOTAL_PROFIT DESC;

-- Q4. Correct comparison: aggregate 2021 actual profit and 2022
-- forecast independently BEFORE joining. Years differ by design.
-- Forecast is a pipeline projection, not realized profit.
WITH actual_2021 AS (
    SELECT CATEGORY, SUM(PROFIT) AS ACTUAL_PROFIT_2021
    FROM SALES
    WHERE YEAR = 2021
    GROUP BY CATEGORY
),
forecast_2022 AS (
    SELECT CATEGORY,
           SUM(FORECAST) AS FORECAST_2022,
           MIN(OPPORTUNITY_AGE) AS NEWEST_OPPORTUNITY_AGE,
           MAX(OPPORTUNITY_AGE) AS OLDEST_OPPORTUNITY_AGE
    FROM FORECASTS
    WHERE YEAR = 2022
    GROUP BY CATEGORY
)
SELECT
    COALESCE(A.CATEGORY, F.CATEGORY) AS CATEGORY,
    A.ACTUAL_PROFIT_2021,
    F.FORECAST_2022,
    F.NEWEST_OPPORTUNITY_AGE,
    F.OLDEST_OPPORTUNITY_AGE,
    ROUND(100.0 * (F.FORECAST_2022 - A.ACTUAL_PROFIT_2021)
        / NULLIF(A.ACTUAL_PROFIT_2021, 0), 2) AS FORECAST_VS_ACTUAL_PCT
FROM actual_2021 A
FULL OUTER JOIN forecast_2022 F ON A.CATEGORY = F.CATEGORY
ORDER BY CATEGORY;
